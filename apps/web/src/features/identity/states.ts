export const INDIAN_STATES = STATE_TABLE.map((s) => s.name) as readonly string[];

const BY_NAME = new Map<string, string>(STATE_TABLE.map((s) => [s.name.toLowerCase(), s.code]));

/** Message key (`states.<code>`) for a stored English state name; undefined for legacy free text. */
export const stateKey = (name: string): string | undefined => BY_NAME.get(name.trim().toLowerCase());

/** Display label for a stored state name: `translate(code)` gives the translation (or undefined); unknown values show as stored. */
export function stateLabel(name: string | null | undefined, translate: (code: string) => string | undefined): string {
  if (!name) return "";
  const key = stateKey(name);
  return (key ? translate(key) : undefined) ?? name;
}

